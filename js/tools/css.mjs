// Compiles less/page.less into a module the lazy page chunk imports, so the
// dossier's styles load with the dossier instead of riding in forum.css on
// every page.
import fs from 'node:fs';
import less from 'less';

const source = fs.readFileSync(new URL('../../less/page.less', import.meta.url), 'utf8');
const { css } = await less.render(source, { compress: true });

// generated/ is not committed, so a fresh checkout makes it here.
fs.mkdirSync(new URL('../generated/', import.meta.url), { recursive: true });
fs.writeFileSync(
  new URL('../generated/pageCss.js', import.meta.url),
  `// Generated by tools/css.mjs from less/page.less. Do not edit.\nexport default ${JSON.stringify(css)};\n`
);
